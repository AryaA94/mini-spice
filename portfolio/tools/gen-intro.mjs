// Writes the G-code for the site's machining intro (intro.nc) and the
// checked copy the page compares against (js/intro-gcode.js).
//
//   node tools/gen-intro.mjs [path/to/gcode-sim]
//
// The program comes from js/fixture.js, worked out from projects.js, so the
// page and this script always agree. With a gcode-sim binary
// (github.com/AryaA94/G-Code), the program is also linted and timed against
// tools/machine.json, and the page shows that result for as long as the
// program it builds is the same one. If the lint finds an error, nothing is
// written.
//
// Re-run this after adding projects that need a new expansion board.

import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import vm from "node:vm";
import { plan, layout, program } from "../js/fixture.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const ctx = { window: {} };
vm.runInNewContext(readFileSync(join(root, "projects.js"), "utf8"), ctx);
const projects = ctx.window.PROJECTS || [];
const p = plan(projects);
const text = program(layout(p.exp.length));

const ncPath = join(root, "intro.nc");
let check = null;
const bin = process.argv[2];
if (bin) {
  const tmp = join(here, "_check.nc");
  writeFileSync(tmp, text);
  const cfg = join(here, "machine.json");
  const run = (args) => {
    try { return execFileSync(bin, args, { encoding: "utf8" }); }
    catch (e) { return e.stdout || ""; }
  };
  const lint = JSON.parse(run(["lint", tmp, "-c", cfg, "--format", "json"]));
  const stats = JSON.parse(run(["stats", tmp, "-c", cfg, "--format", "json"]));
  execFileSync("rm", ["-f", tmp]);
  for (const d of lint.diagnostics) console.log(`intro.nc:${d.line}: ${d.severity}[${d.code}] ${d.message}`);
  if (lint.errors > 0) { console.error("gcode-sim found errors; nothing written."); process.exit(1); }
  check = { lint: { errors: lint.errors, warnings: lint.warnings }, stats: { lines: stats.lines, time_s: stats.time_s } };
  console.log(`gcode-sim: ${lint.errors} errors, ${lint.warnings} warnings, ${Math.round(stats.time_s.total)} s`);
}

writeFileSync(ncPath, text);
writeFileSync(
  join(root, "js", "intro-gcode.js"),
  "// Generated by tools/gen-intro.mjs. Do not edit by hand.\n" +
    `export const CHECK = ${JSON.stringify(check)};\n` +
    `export const GCODE = ${JSON.stringify(text)};\n`
);
console.log(`${projects.length} projects, ${p.exp.length} expansion boards, ${text.split("\n").length - 1} lines written to intro.nc`);
